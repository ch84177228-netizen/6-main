# ── 生成 txt ──────────────────────────────────────────────────────────────────

def make_txt(title, body, topics, account):
    return f'标题：{title}\n\n正文：\n{body}\n\n话题：{topics}\n\n时间：\n\n账号：{account}\n'

base = Path('./合并抵消底层逻辑_发布文案')
base.mkdir(exist_ok=True)

for i in range(6):
    folder = base / GROUPS[i]
    folder.mkdir(exist_ok=True)

    xhs_name = xhs_accounts[i].split('|')[1]
    (folder / f'2_小红书_{xhs_name}.txt').write_text(
        make_txt(TITLES[i], BODIES[i], TOPICS[i], xhs_accounts[i]), encoding='utf-8')

    if i < 5:
        dy_name = dy_accounts[i].split('|')[1]
        (folder / f'1_抖音_{dy_name}.txt').write_text(
            make_txt(TITLES[i], BODIES[i], TOPICS[i], dy_accounts[i]), encoding='utf-8')

    sp_name = sp_accounts[i].split('|')[1]
    (folder / f'4_视频号_{sp_name}.txt').write_text(
        make_txt(TITLES[i], BODIES[i], TOPICS[i], sp_accounts[i]), encoding='utf-8')

    if i < 4:
        gzh_name = gzh_accounts[i].split('|')[1]
        (folder / f'13_公众号_{gzh_name}.txt').write_text(
            make_txt(TITLES[i], BODIES[i], TOPICS[i], gzh_accounts[i]), encoding='utf-8')

txt_count = sum(1 for _ in base.rglob('*.txt'))
print(f'✅ txt文件生成完成，共 {txt_count} 个')

# ── 生成 Word ─────────────────────────────────────────────────────────────────

doc = Document()
for section in doc.sections:
    section.top_margin    = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin   = Cm(2.5)
    section.right_margin  = Cm(2.5)

cover = doc.add_paragraph()
cover.alignment = WD_ALIGN_PARAGRAPH.CENTER
r = cover.add_run('合并报表抵消底层逻辑\n6账号完整图文脚本')
r.bold = True
r.font.size = Pt(20)
doc.add_paragraph()
sub = doc.add_paragraph()
sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
sub.add_run('诗雨学姐·内容运营系统\n合并报表系列·第②篇\n2026年5月').font.size = Pt(12)
doc.add_page_break()

for idx, s in enumerate(SCRIPTS):
    h1 = doc.add_heading(s['account'], level=1)
    h1.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p = doc.add_paragraph()
    r = p.add_run(f'标题：{s["title"]}')
    r.bold = True
    r.font.size = Pt(13)
    doc.add_paragraph()

    for slide_title, slide_body in s['slides']:
        h2 = doc.add_heading(slide_title, level=2)
        h2.alignment = WD_ALIGN_PARAGRAPH.LEFT
        for line in slide_body.split('\n'):
            p2 = doc.add_paragraph(line)
            p2.paragraph_format.space_after = Pt(2)
            for run in p2.runs:
                run.font.size = Pt(11)
        doc.add_paragraph()

    if idx < len(SCRIPTS) - 1:
        doc.add_page_break()

word_path = '合并抵消底层逻辑_6账号完整脚本.docx'
doc.save(word_path)
print(f'✅ Word文档生成完成：{word_path}')

