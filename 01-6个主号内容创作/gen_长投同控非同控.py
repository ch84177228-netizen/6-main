def add_word(doc, key, account_label):
    title, body = bodies[key]
    h = doc.add_heading(f"账号{key}　{account_label}", level=1)
    p = doc.add_paragraph()
    run = p.add_run(f"已选标题：{title}")
    run.bold = True
    doc.add_paragraph("")
    for line in body.split("\n"):
        if line.strip() == "":
            doc.add_paragraph("")
        elif line.startswith("【") or (line.startswith("✅") and "模块" in line):
            hp = doc.add_paragraph()
            r = hp.add_run(line)
            r.bold = True
        else:
            para = doc.add_paragraph(line)
            para.style.font.size = Pt(11)
    doc.add_paragraph("—" * 30)

