def add_heading_doc(doc, text, level):
    p = doc.add_paragraph(text)
    p.style = doc.styles[f'Heading {level}']
    return p

def add_body_doc(doc, text):
    for line in text.strip().split('\n'):
        doc.add_paragraph(line if line.strip() else '')

def make_word(word_list, cover_title, filename):
    doc = Document()
    style = doc.styles['Normal']
    style.font.name = '微软雅黑'
    style.font.size = Pt(11)

    # 封面
    doc.add_paragraph('')
    p = doc.add_paragraph('成本管理（中级财务管理·第8章）')
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.runs[0]
    run.font.size = Pt(22)
    run.bold = True

    p = doc.add_paragraph(cover_title)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.runs[0]
    run.font.size = Pt(16)

    p = doc.add_paragraph(f'12账号全套脚本  |  2026年6月12日  |  距考试{COUNTDOWN}天')
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_page_break()

    for account_label, title, script in word_list:
        add_heading_doc(doc, account_label, 1)
        lines = script.strip().split('\n')
        filtered = []
        for line in lines:
            if line.strip().startswith(('标题1：', '标题2：', '标题3：', '标题4：', '标题5：', '【标题备选】')):
                continue
            if line.strip().startswith('【已选标题】'):
                selected_title = line.strip().replace('【已选标题】', '').strip()
                add_heading_doc(doc, f'已选标题：{selected_title}', 2)
                continue
            filtered.append(line)
        add_body_doc(doc, '\n'.join(filtered))
        doc.add_page_break()

    docx_path = os.path.join(BASE, filename)
    os.makedirs(BASE, exist_ok=True)
    doc.save(docx_path)
    print(f"✅ Word文档已生成：{docx_path}")

