def save(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

def write_txt(path, title, body, topics, account):
    tc = len(title)
    bc = len(body.replace("\n","").replace(" ",""))
    ok = "✅" if tc<=20 and bc<=150 else f"❌(标题{tc},正文{bc}字)"
    print(f"  {ok} 标题{tc}字 正文{bc}字 | {account.split('|')[-1]}")
    save(path, f"标题：{title}\n\n正文：\n{body}\n\n话题：{topics}\n\n时间：\n\n账号：{account}\n")

def add_word_content(doc, content):
    for line in content.strip().split("\n"):
        p = doc.add_paragraph()
        run = p.add_run(line)
        run.font.size = Pt(12)
        if any(line.startswith(x) for x in ["一、","二、","三、","四、","五、","六、","七、","八、","九、","十、"]):
            run.bold = True

def make_zip():
    zip_path = os.path.join(BASE, "租赁_全套发布文案.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(BASE):
            for file in files:
                if file.endswith(".zip"):
                    continue
                full = os.path.join(root, file)
                arcname = os.path.relpath(full, BASE)
                zf.write(full, arcname)
    return zip_path

