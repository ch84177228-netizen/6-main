def add_word_content(doc, content):
    for line in content.strip().split("\n"):
        p = doc.add_paragraph(); run = p.add_run(line); run.font.size = Pt(12)
        if any(line.startswith(x) for x in ["一、","二、","三、","四、","五、","六、","七、","八、"]):
            run.bold = True

