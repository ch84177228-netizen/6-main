def make_txt(a):
    return (
        f"标题：{a['title']}\n"
        f"\n"
        f"正文：\n"
        f"{a['body']}\n"
        f"\n"
        f"话题：{a['tags']}\n"
        f"\n"
        f"时间：\n"
        f"\n"
        f"账号：{a['account']}\n"
    )

txt_paths = []
for a in articles:
    fname = f"{a['no']:02d}_{a['platform']}_{a['title']}.txt"
    fpath = os.path.join(BASE, fname)
    with open(fpath, "w", encoding="utf-8") as f:
        f.write(make_txt(a))
    txt_paths.append(fpath)
    body_len = len(a["body"].replace("\n", ""))
    print(f"✅ {a['no']:02d} [{a['platform']}] {a['title']} ({body_len}字)")

