def self_check():
    print("\n=== 自检 ===")
    ok = True
    g = os.path.join(BASE, "01-主题")
    for root, dirs, files in os.walk(g):
        for fn in files:
            full = os.path.join(root, fn)
            with open(full, encoding="utf-8") as f:
                content = f.read()
            prefix = fn.split("_")[0]
            expect = {"07":"07抖音发作品","06":"06红书店铺","04":"04视频号","13":"13公众号"}[prefix]
            if expect not in content:
                print(f"  ❌ 前缀不符：{full}"); ok = False
            for b in BANNED:
                if b in content:
                    print(f"  ❌ 含禁用语[{b}]：{full}"); ok = False
    txt_count = sum(len(files) for _, _, files in os.walk(g))
    print(f"  txt总数：{txt_count}（应为31）")
    if txt_count != 31: ok = False
    print("  ✅ 自检通过" if ok else "  ❌ 自检未通过，请检查以上问题")
