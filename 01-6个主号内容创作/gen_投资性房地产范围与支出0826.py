def save(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

def write_txt(path, title, body, topics, account):
    tc = len(title); bc = len(body.replace("\n","").replace(" ",""))
    ok = "OK" if tc<=20 and bc<=150 else f"BAD(title{tc},body{bc})"
    print(f"  {ok} title{tc} body{bc} | {account.split('|')[-1]}")
