def build():
    doc = Document()
    title = doc.add_heading("今日5篇章节样稿审核", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub = doc.add_paragraph("日期：2026-07-06")
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for i, ch in enumerate(CHAPTERS):
        run = doc.add_paragraph().add_run()
        run.add_break(WD_BREAK.PAGE)

        h1 = doc.add_heading(f"第{i+1}篇　科目：{ch['subject']}　｜　章节：{ch['name']}", level=1)

        for sec_title, sec_body in ch["sections"]:
            doc.add_heading(sec_title, level=2)
            for line in sec_body.split("\n"):
                p = doc.add_paragraph()
                r = p.add_run(line)
                r.font.size = Pt(12)

    doc.save(OUT)
    print(f"✅ 已生成：{OUT}")

