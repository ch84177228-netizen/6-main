def make_txt(title, body, topics, account):
    return f"标题：{title}\n\n正文：\n{body}\n\n话题：{topics}\n\n时间：\n\n账号：{account}\n"

def write_txt(path, title, body, topics, account):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    content = make_txt(title, body, topics, account)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    chars = len(body.replace('\n','').replace(' ',''))
    return chars

